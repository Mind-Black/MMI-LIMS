-- Backfill legacy bookings missing end_time or range timestamps
-- Handles midnight rollover cleanly (e.g. 23:30 + 30m rolls into 00:00 of the next calendar day)
UPDATE public.bookings
SET
  starts_at = (date::text || ' ' || time::text)::timestamp AT TIME ZONE 'Europe/Vilnius',
  ends_at = (date::text || ' ' || time::text)::timestamp AT TIME ZONE 'Europe/Vilnius' + 
    CASE 
      WHEN end_time IS NOT NULL AND end_time > time THEN (end_time - time)
      ELSE interval '30 minutes'
    END
WHERE starts_at IS NULL OR ends_at IS NULL;

-- Synchronize end_time to match ends_at
UPDATE public.bookings
SET end_time = (ends_at AT TIME ZONE 'Europe/Vilnius')::time
WHERE end_time IS NULL;

