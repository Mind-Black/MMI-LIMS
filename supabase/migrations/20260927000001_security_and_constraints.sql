  FOR UPDATE
  USING (auth.uid() IS NULL OR auth.uid() = user_id OR public.is_admin(auth.uid()))
  WITH CHECK (auth.uid() IS NULL OR auth.uid() = user_id OR public.is_admin(auth.uid()));

CREATE POLICY "bookings_delete_own_or_admin" ON public.bookings
  FOR DELETE
  USING (auth.uid() IS NULL OR auth.uid() = user_id OR public.is_admin(auth.uid()));

