  FOR SELECT
  USING (
    auth.uid() IS NULL
    OR public.is_approved_user(auth.uid()) 
    OR public.is_admin(auth.uid())
  );

CREATE POLICY "bookings_insert_own" ON public.bookings
  FOR INSERT
  WITH CHECK (
    auth.uid() IS NULL
    OR (public.is_approved_user(auth.uid()) AND auth.uid() = user_id)
    OR public.is_admin(auth.uid())
  );

