-- 2. Ensure base tables exist
CREATE TABLE IF NOT EXISTS public.tools (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  category text NOT NULL,
  status text NOT NULL DEFAULT 'up' CHECK (status IN ('up', 'down', 'service')),
  location text,
  license_req boolean NOT NULL DEFAULT true,
  description text
);

CREATE TABLE IF NOT EXISTS public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  first_name text,
  last_name text,
  access_level text NOT NULL DEFAULT 'user' CHECK (access_level IN ('user', 'admin')),
  is_approved boolean NOT NULL DEFAULT false,
  licenses jsonb NOT NULL DEFAULT '[]'::jsonb,
  projects text[] NOT NULL DEFAULT '{}'::text[],
  updated_at timestamptz DEFAULT timezone('utc'::text, now())
);

CREATE TABLE IF NOT EXISTS public.bookings (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tool_id bigint NOT NULL REFERENCES public.tools(id) ON DELETE CASCADE,
  tool_name text NOT NULL,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  user_name text NOT NULL,
  project text NOT NULL DEFAULT 'General',
  date date NOT NULL,
  time time NOT NULL,
  end_time time,
  created_at timestamptz NOT NULL DEFAULT timezone('utc'::text, now())
);

