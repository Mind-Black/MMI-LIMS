-- PROFILES (Fixes R8)
-- Direct SQL Editor / service role / migrations (auth.uid() IS NULL) have full access.
-- Pending users can only see their own profile.
-- Approved users and admins can see directory profiles.
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profiles FORCE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "profiles_select_authenticated" ON public.profiles;
DROP POLICY IF EXISTS "profiles_select_policy" ON public.profiles;
DROP POLICY IF EXISTS "profiles_update_self_or_admin" ON public.profiles;
DROP POLICY IF EXISTS "profiles_admin_all" ON public.profiles;

CREATE POLICY "profiles_select_policy" ON public.profiles
  FOR SELECT
  USING (
    auth.uid() IS NULL
    OR (auth.uid() = id) 
    OR public.is_approved_user(auth.uid()) 
    OR public.is_admin(auth.uid())
  );

CREATE POLICY "profiles_update_self_or_admin" ON public.profiles
  FOR UPDATE
  USING (auth.uid() IS NULL OR auth.uid() = id OR public.is_admin(auth.uid()))
  WITH CHECK (auth.uid() IS NULL OR auth.uid() = id OR public.is_admin(auth.uid()));

CREATE POLICY "profiles_admin_all" ON public.profiles
  FOR ALL
  USING (auth.uid() IS NULL OR public.is_admin(auth.uid()));

